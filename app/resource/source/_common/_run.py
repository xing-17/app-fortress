from __future__ import annotations

from typing import Any, ClassVar, Self

from pydantic import Field, model_validator

from app.internal.abstract.domain import IAbstractDomain
from app.internal.constant.computestatus import ComputeStatus
from app.internal.util.clock import IClock
from app.internal.util.id import IID


class DatasetRun(IAbstractDomain):
    """
    Record of a single dataset run, persisted in the dataset database keyed by `id`

    Lifecycle: STARTED -> COMPLETED | FAILED, a terminal run never changes again.

    Args:
    ----------
        id (str):
            Run identifier, generated locally
        status (ComputeStatus):
            Current status, STARTED until the run completes or fails
        provider (str):
            Source provider of the dataset
        dataset (str):
            Name of the dataset
        params (dict[str, Any]):
            JSON parameters the run was called with
        assetfiles (list[str]):
            URIs of the assetfiles written by a completed run, empty otherwise
        height (int | None):
            Rows of the dataframe written by a completed run
        width (int | None):
            Columns of the dataframe written by a completed run
        error (str | None):
            Failure message of a failed run, None otherwise
        started_at (float | None):
            Start timestamp, in UTC, defaults to the creation time
        finished_at (float | None):
            Timestamp at which the run completed or failed, in UTC

    Attributes:
    ----------
        is_finished (bool):
            Whether the run has reached a terminal status
        duration (float):
            Seconds from start to finish, or to now if still running

    Methods:
    ----------
        complete(assetfiles: list[str], height: int, width: int) -> None:
            Mark the run as completed with its output.
        fail(error: Exception | str | None = None) -> None:
            Mark the run as failed with the given error.

    Raises:
    ----------
        ValueError:
            When `complete` or `fail` is called on a finished run

    """

    _transitions: ClassVar[dict[ComputeStatus, frozenset[ComputeStatus]]] = {
        ComputeStatus.STARTED: frozenset({ComputeStatus.COMPLETED, ComputeStatus.FAILED}),
    }

    id: str = Field(
        default_factory=lambda: IID.generate_id(prefix="run", length=16),
        min_length=1,
        description="The unique identifier of the dataset run",
    )
    status: ComputeStatus = Field(
        default=ComputeStatus.STARTED,
        description="The current status of the dataset run",
    )
    provider: str = Field(
        ...,
        description="The provider of the dataset run",
    )
    dataset: str = Field(
        ...,
        description="The dataset associated with the run",
    )
    params: dict[str, Any] = Field(
        default_factory=dict,
        description="The parameters used for the dataset run",
    )
    assetfiles: list[str] = Field(
        default_factory=list,
        description="The list of asset files generated by the dataset run",
    )
    height: int | None = Field(
        default=None,
        description="The height of the dataset run output",
    )
    width: int | None = Field(
        default=None,
        description="The width of the dataset run output",
    )
    error: str | None = Field(
        default=None,
        description="The error message if the dataset run failed",
    )
    started_at: float | None = Field(
        default=None,
        description="The timestamp when the dataset run started",
    )
    finished_at: float | None = Field(
        default=None,
        description="The timestamp when the dataset run finished",
    )

    @model_validator(mode="after")
    def _derive_started_at(self) -> Self:
        if self.started_at is None:
            object.__setattr__(self, "started_at", self._current())
        return self

    @property
    def is_finished(self) -> bool:
        return self.status in (ComputeStatus.COMPLETED, ComputeStatus.FAILED)

    @property
    def duration(self) -> float:
        if self.finished_at is not None:
            _end = self.finished_at
        else:
            _end = self._current()
        return _end - self.started_at

    def _current(self) -> float:
        return IClock.current_timestamp(timezone="UTC")

    def _check_transition(
        self,
        new: ComputeStatus,
    ) -> None:
        if new not in self._transitions.get(self.status, frozenset()):
            raise ValueError(f"Transit from '{self.status}' to '{new}' not allowed")

    def complete(
        self,
        assetfiles: list[str],
        height: int,
        width: int,
    ) -> None:
        self._check_transition(ComputeStatus.COMPLETED)
        self.status = ComputeStatus.COMPLETED
        self.finished_at = self._current()
        self.assetfiles, self.height, self.width = assetfiles, height, width

    def fail(
        self,
        error: Exception | str | None = None,
    ) -> None:
        self._check_transition(ComputeStatus.FAILED)
        self.status = ComputeStatus.FAILED
        self.finished_at = self._current()
        self.error = str(error or "Unknown error")
